#!/usr/bin/env bash
# Keep the player running on a machine that is always on, reachable by your own
# devices and nobody else's.
#
#   ./ops/install-player-linux.sh
#
# Undo with:
#
#   systemctl --user disable --now balerion-serve
#   rm ~/.config/systemd/user/balerion-serve.service ~/.config/balerion/serve.env
#
# The macOS equivalent is install-player.sh. This one differs in two ways that
# are not cosmetic: it binds to the network rather than to loopback, because the
# point of an always-on machine is that a phone can reach it, and it therefore
# generates a token, because the endpoint it exposes downloads whatever magnet
# it is handed.
set -euo pipefail

BINARY="${BINARY:-$HOME/.cargo/bin/balerion}"
UNIT_DIR="$HOME/.config/systemd/user"
CONF_DIR="$HOME/.config/balerion"
ENV_FILE="$CONF_DIR/serve.env"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

if [ ! -x "$BINARY" ]; then
  echo "no balerion binary at $BINARY" >&2
  echo "either 'cargo install --path crates/balerion-cli' or set BINARY=..." >&2
  exit 1
fi

# ffmpeg is optional to the program and not optional to the point of this
# exercise: without it, anything that is not already MP4 is offered as a
# download rather than played, and most of what you will want to watch is MKV.
if ! command -v ffmpeg >/dev/null 2>&1; then
  echo "warning: no ffmpeg on PATH." >&2
  echo "         MKV and similar will be offered as downloads rather than played." >&2
  echo "         apt install ffmpeg  (or your distribution's equivalent)" >&2
fi

# Prefer the Tailscale address to 0.0.0.0. On a laptop that is the difference
# between "my own devices can reach it" and "everyone on this network can try",
# and it means the token is a second line rather than the only one.
HOST="${BALERION_HOST:-}"
if [ -z "$HOST" ]; then
  if command -v tailscale >/dev/null 2>&1; then
    HOST="$(tailscale ip -4 2>/dev/null | head -1 || true)"
  fi
  HOST="${HOST:-0.0.0.0}"
fi

mkdir -p "$UNIT_DIR" "$CONF_DIR"

# A token that survives restarts, so the link on a phone keeps working. Kept in
# a file of its own, readable only by you, so the unit can be committed and read
# without carrying a credential.
if [ -f "$ENV_FILE" ] && grep -q '^BALERION_TOKEN=' "$ENV_FILE"; then
  echo "keeping the existing token in $ENV_FILE"
  TOKEN="$(grep '^BALERION_TOKEN=' "$ENV_FILE" | cut -d= -f2-)"
else
  TOKEN="$(head -c 16 /dev/urandom | od -An -tx1 | tr -d ' \n')"
fi

umask 077
cat > "$ENV_FILE" <<EOF
# Read by balerion-serve.service. Generated by install-player-linux.sh.
#
# The token is required of every request that did not come from this machine.
# Anyone holding it can make this machine download things and delete what you
# are watching, so it is a credential rather than a setting.
BALERION_HOST=$HOST
BALERION_TOKEN=$TOKEN
EOF

install -m 644 "$HERE/balerion-serve.service" "$UNIT_DIR/balerion-serve.service"

systemctl --user daemon-reload
systemctl --user enable --now balerion-serve

# So it keeps running when you are not logged in, which on an always-on machine
# is the entire point. Needs no password if it has been granted before.
if command -v loginctl >/dev/null 2>&1; then
  loginctl enable-linger "$USER" 2>/dev/null ||
    echo "note: could not enable lingering; the player will stop when you log out." >&2
fi

echo
echo "balerion-serve is running, bound to $HOST"
echo
echo "Open this once on each device that should be allowed in:"
echo
echo "  http://$HOST:8080/?balerion_token=$TOKEN"
echo
echo "It sets a cookie for a year. Requests from this machine are never asked."
echo "Point the search site's BALERION_LOCAL_URL at http://$HOST:8080"
echo
echo "  systemctl --user status balerion-serve     what it is doing"
echo "  journalctl --user -u balerion-serve -f     what it is saying"
